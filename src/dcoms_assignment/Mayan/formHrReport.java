    private void btnGenerateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblEmployees.getSelectedRow();
        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select an employee!");
            return;
        }
        int employeeID = (int) tblEmployees.getValueAt(selectedRow, 0);
        if (cmbYear.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a year!");
            return;
        }
        int year = Integer.parseInt(cmbYear.getSelectedItem().toString());
        try {
            String filePath = remote.exportLeaveReport(employeeID, year);
            if (filePath != null && !filePath.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Export successful!\nFile: " + filePath);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Export failed!");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Server error during export!");
        }
    }//GEN-LAST:event_btnGenerateActionPerformed

