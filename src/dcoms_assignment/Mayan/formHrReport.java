    private void loadEmployeesTable() {
        try {
            List<Employee> list = remote.getAllEmployees();
            DefaultTableModel model = (DefaultTableModel) tblEmployees.getModel();
            model.setRowCount(0);
            for (Employee e : list) {
                model.addRow(new Object[]{
                    e.getEmployeeID(),
                    e.getFirstName(),
                    e.getLastName(),
                    e.getIcOrPassportNo()
                });
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to load employees");
        }
    }
    
    private void tableRowClicked() {
        int selectedRow = tblEmployees.getSelectedRow();
        if (selectedRow == -1) return;
        int employeeID = (int) tblEmployees.getValueAt(selectedRow, 0);
        try {
            List<Integer> years = remote.getLeaveYearsByEmployee(employeeID);
            cmbYear.removeAllItems();
            for (int year : years) {
                cmbYear.addItem(String.valueOf(year));
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to load years");
        }
    }

